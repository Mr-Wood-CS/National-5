CREATE TABLE Golfer (
  scotGolfNo INT NOT NULL PRIMARY KEY,
  forename VARCHAR(255) NOT NULL,
  surname VARCHAR(255) NOT NULL,
  age VARCHAR(255) NOT NULL,
  club VARCHAR(255) NOT NULL,
  handicap INT
