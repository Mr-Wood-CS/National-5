  type VARCHAR(255) NOT NULL,
  year INT NOT NULL,
  score INT NOT NULL,
  scotGolfNo INT NOT NULL,
  matchType VARCHAR(255) NOT NULL,
  FOREIGN KEY (scotGolfNo) REFERENCES Golfer(scotGolfNo)
